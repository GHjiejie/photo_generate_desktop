const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const {version,build}=require('../package.json');
const output=path.resolve(__dirname,'..',build.directories.output);
const packagePath=`Portrait-Studio-React-${version}-arm64.zip`;
const bytes=fs.readFileSync(path.join(output,packagePath));
const manifest={version,name:`Portrait Studio ${version}`,notes:'保留原深色 React 图库、完整双语提示词与本地素材增删改；新增左下角本地版本检查、更新包校验及确认后升级流程。当前包为本地 ad-hoc 签名，未公证，实际 Gatekeeper 拒绝时不会自动安装。',pub_date:new Date().toISOString(),packagePath,sha256:crypto.createHash('sha256').update(bytes).digest('hex'),size:bytes.length,platform:'darwin',arch:'arm64',bundleId:build.appId};
fs.writeFileSync(path.join(output,'updates.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(`Wrote ${path.join(output,'updates.json')} with actual ZIP SHA-256`);
